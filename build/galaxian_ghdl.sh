# galaxian_ghdl.sh -- the core's VHDL (the T80, build/galaxian_files.sh) as a Verilog netlist made by GHDL's
# synthesis, so the Gowin build and the sims compile the same logic instead of handing GowinSynthesis the VHDL
# directly (its VHDL front end has built designs wrongly on silicon; scramble-tango and galaga-tango use the same
# route).
#   build/galaxian_ghdl.sh <outdir>    -> <outdir>/T80se.v, T80se_t2w.v, ghdl_version.txt, sha256.txt, *.log
#
# The files are analysed from copies in <outdir>/work/src with two changes; rtl/galaxian/ itself is never edited:
#   1. T80.vhd's block-I/O flag line `ioq := (ioq and x"7") xor ('0'&BusA);` ANDs the 9-bit ioq with a 4-bit literal;
#      GHDL requires equal lengths, so the copy reads `9x"7"` (bits 2:0 kept, the Z80's (sum & 7) xor B).
#   2. T80.vhd's `Auto_Wait <= '1' when (IntCycle = '1' or NMICycle = '1') and MCycle = "001"` gives the NMI
#      acknowledge M1 the two automatic wait states of the INT acknowledge, so an NMI response takes 13 T.  The Z80's
#      NMI response is 11 T (a 5-T M1 whose data is ignored, then the two 3-T PC pushes; Zilog Z80 CPU User Manual,
#      "Non-Maskable Interrupt Response"; MAME's Z80 and T80 0247 agree), so the copy reads
#      `Auto_Wait <= '1' when IntCycle = '1' and MCycle = "001"`.
# The script checks that each change applied exactly once.
#
# Then, per unit of GX_UNITS: ghdl --synth (-fsynopsys --std=08 -frelaxed) of its entity with its generics
# (GX_UNIT_<unit> in build/galaxian_files.sh; Mode 0 = Z80 throughout), tools/ghdl_fix_verilog.py for GHDL 4.1's
# Verilog-printer defects, for a unit named other than its entity tools/ghdl_suffix_modules.py (top module = the unit
# name, sub-modules suffixed, so that T80se and T80se_t2w compile side by side), and a verilator --lint-only of the
# result (0 errors is the gate).  GHDL runs under sys/build_tools/tango_capped.sh (a memory cap, TANGO_MEM_CAP).
set -eu
[ $# -eq 1 ] || { sed -n "4,/^set -eu/{/^#/p}" "$0"; exit 2; }
OUT="$1"; mkdir -p "$OUT"; OUT="$(cd "$OUT" && pwd)"
cd "$(dirname "$0")/.."
ROOT="$(pwd)"
. "$ROOT/build/galaxian_files.sh"
CAPPED="$ROOT/sys/build_tools/tango_capped.sh"
export TANGO_MEM_CAP="${TANGO_MEM_CAP:-4G}"
for f in $GX_VHDL; do [ -f "$f" ] || { echo "galaxian_ghdl.sh: missing $f" >&2; exit 1; }; done
W="$OUT/work"; rm -rf "$W"; mkdir -p "$W/src"
(cd "$OUT" && rm -f ./*.v analyse.log synth_*.log fix.log lint_*.log ghdl_version.txt sha256.txt)

COPIES=""
for f in $GX_VHDL; do
    c="$W/src/$(basename "$f")"
    sed -e 's/ioq and x"7"/ioq and 9x"7"/' \
        -e "s/Auto_Wait <= '1' when (IntCycle = '1' or NMICycle = '1') and MCycle/Auto_Wait <= '1' when IntCycle = '1' and MCycle/" \
        "$f" > "$c"
    if [ "$(basename "$f")" = T80.vhd ]; then
        [ "$(grep -c 'ioq and 9x"7"' "$c")" = 1 ] ||
            { echo "galaxian_ghdl.sh: the T80.vhd ioq rewrite did not match exactly once" >&2; exit 1; }
        [ "$(grep -c "Auto_Wait <= '1' when IntCycle = '1' and MCycle" "$c")" = 1 ] ||
            { echo "galaxian_ghdl.sh: the T80.vhd NMI Auto_Wait rewrite did not match exactly once" >&2; exit 1; }
    fi
    COPIES="$COPIES $c"
done

GF="-fsynopsys --std=08 -frelaxed --workdir=$W"
"$CAPPED" ghdl -a $GF $COPIES 2> "$OUT/analyse.log" || { cat "$OUT/analyse.log"; exit 1; }
VER="$(ghdl --version | head -1)"
echo "$VER" > "$OUT/ghdl_version.txt"
for u in $GX_UNITS; do
    eval "spec=\"\${GX_UNIT_$u:-$u}\""
    ent="${spec%% *}"; gen="${spec#"$ent"}"
    # shellcheck disable=SC2086  # $gen: zero or more -g options
    "$CAPPED" ghdl --synth $GF $gen --out=verilog $ent > "$W/${u}_raw.v" 2> "$OUT/synth_$u.log" ||
        { tail -40 "$OUT/synth_$u.log"; exit 1; }
    python3 tools/ghdl_fix_verilog.py "$W/${u}_raw.v" "$W/${u}.v" 2>> "$OUT/fix.log" || { cat "$OUT/fix.log"; exit 1; }
    POST="tools/ghdl_fix_verilog.py"
    if [ "$u" != "$ent" ]; then
        mv "$W/${u}.v" "$W/${u}_fixed.v"
        python3 tools/ghdl_suffix_modules.py "$W/${u}_fixed.v" "$W/${u}.v" "$u" "${u#"$ent"_}" 2>> "$OUT/fix.log" ||
            { cat "$OUT/fix.log"; exit 1; }
        POST="$POST and tools/ghdl_suffix_modules.py"
    fi
    { echo "// $u.v -- GENERATED by build/galaxian_ghdl.sh; do not edit.  GHDL synthesis of the VHDL below (licences:"
      echo "// the sources' headers, NOTICE), post-processed by $POST."
      echo "// $VER"
      echo "// ghdl --synth -fsynopsys --std=08 -frelaxed$gen --out=verilog $ent"
      for f in $GX_VHDL; do echo "// sha256 $(sha256sum "$f" | cut -c1-64) ${f#$ROOT/}"; done
      for c in $COPIES; do echo "// sha256 $(sha256sum "$c" | cut -c1-64) (analysed copy) $(basename "$c")"; done
      cat "$W/$u.v"; } > "$OUT/$u.v"
    TOP=$(grep -oE '^module [A-Za-z0-9_]+' "$W/$u.v" | tail -1 | cut -d' ' -f2)   # GHDL prints the top last
    [ "$(echo "$TOP" | tr A-Z a-z)" = "$(echo "$u" | tr A-Z a-z)" ] ||
        { echo "galaxian_ghdl.sh: last module in $u.v is $TOP, not $u" >&2; exit 1; }
    verilator --lint-only -Wno-fatal --top-module "$TOP" "$OUT/$u.v" > "$OUT/lint_$u.log" 2>&1 ||
        { echo "galaxian_ghdl.sh: verilator --lint-only FAILED on $u:"; cat "$OUT/lint_$u.log"; exit 1; }
    NERR=$(grep -c '^%Error' "$OUT/lint_$u.log" || true)
    [ "$NERR" = 0 ] || { echo "galaxian_ghdl.sh: $NERR verilator error(s) in $u:"; cat "$OUT/lint_$u.log"; exit 1; }
    echo "galaxian_ghdl.sh: $u.v (module $TOP): verilator --lint-only 0 errors ($(grep -c '^%Warning' "$OUT/lint_$u.log" || true) warnings)"
done
(cd "$OUT" && sha256sum $(for u in $GX_UNITS; do echo $u.v; done) > sha256.txt)
grep -h -E 'renamed|tied|merged|dropped|assigns' "$OUT/fix.log" | sed 's/^/  /' || true
echo "galaxian_ghdl.sh: $OUT: $(for u in $GX_UNITS; do printf '%s.v ' $u; done)($VER)"
